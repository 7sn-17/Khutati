-- In-app update manifest read by the Flutter client.
--
-- The client queries this table first (PostgREST, anon key), and falls back to
-- GitHub Releases if the request fails or the table has no published row.
-- Only public release metadata lives here: never store user data.

create table if not exists public.app_updates (
  id bigint generated by default as identity primary key,
  platform text not null default 'android',
  channel text not null default 'stable',
  version_name text not null,
  version_code integer not null,
  apk_url text not null,
  notes text,
  mandatory boolean not null default false,
  min_supported_version text,
  published_at timestamptz not null default now()
);

create index if not exists idx_app_updates_lookup
  on public.app_updates (platform, channel, published_at desc);

alter table public.app_updates enable row level security;

-- The manifest is public by design; writes stay in the dashboard/service role.
drop policy if exists app_updates_public_read on public.app_updates;
create policy app_updates_public_read
  on public.app_updates
  for select
  to anon, authenticated
  using (true);

